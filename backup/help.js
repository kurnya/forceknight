function normalizeTopicKey(value) {
  return (value || "").trim().toLowerCase();
}

const sepuhAudioPath = path.resolve(__dirname, "../../audio/sepuh.ogg");

module.exports = {
  name: "help",
  description: "Menampilkan bantuan penggunaan bot.",
  topicReplies,
  normalizeTopicKey,
  execute: async ({ sock, message, args = [] }) => {
    const normalizedArg = normalizeTopicKey(args[0]);
    const topicReply = topicReplies[normalizedArg];
    const topicKey = topicReply ? normalizedArg : "menu";
    const text = normalizedArg === "#98" || normalizedArg === "#99"
      ? normalizeSpacing(topicReply || "")
      : formatHelpMessage(topicReply || helpMenuText, topicKey);

    if (normalizedArg === "#98") {
      await sock.sendMessage(
        message.key.remoteJid,
        {
          audio: fs.readFileSync(sepuhAudioPath),
          mimetype: "audio/ogg; codecs=opus",
          ptt: true
        },
        {
          quoted: message
        }
      );
    }

    if (normalizedArg === "#99") {
      const senderName =
        message.pushName ||
        message.key?.participant?.split("@")[0] ||
        message.key?.remoteJid?.split("@")[0] ||
        "onii-chan";
      const { percentage, response, opener } = getRandomLuckResult();

      await sock.sendMessage(
        message.key.remoteJid,
        {
          text: [
            opener,
            "",
            `Tes kehokian untuk ${senderName} yaa~ (≧◡≦)`,
            `Hasil hoki hari ini: *${percentage}%* (๑˃ᴗ˂)ﻭ`,
            "",
            response
          ].join("\n")
        },
        {
          quoted: message
        }
      );

      return;
    }

    await sock.sendMessage(
      message.key.remoteJid,
      {
        text
      },
      {
        quoted: message
      }
    );
  }
};
