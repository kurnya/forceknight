function getRandomCuteFooter() {
  return cuteFooterQuestions[Math.floor(Math.random() * cuteFooterQuestions.length)];
}

function getRandomGreetingLines() {
  return dynamicGreetings[Math.floor(Math.random() * dynamicGreetings.length)];
}

function getRandomIntro(topicKey) {
  const intros = topicHeaderIntros[topicKey] || topicHeaderIntros.default;
  return intros[Math.floor(Math.random() * intros.length)];
}

function getRandomLuckResult() {
  const percentage = luckPercentages[Math.floor(Math.random() * luckPercentages.length)];
  const responses = hokiResponses[percentage];
  const response = responses[Math.floor(Math.random() * responses.length)];
  const opener = luckOpeners[Math.floor(Math.random() * luckOpeners.length)];

  return {
    percentage,
    response,
    opener
  };
}

function isLegacyDivider(line) {
  const trimmed = line.trim();

  if (!trimmed) {
    return false;
  }

  if (/^[\-‐—_]{8,}$/.test(trimmed)) {
    return true;
  }

  if (/^[━─]{8,}$/.test(trimmed)) {
    return true;
  }

  if (/^[󠇖\s]+$/.test(trimmed)) {
    return true;
  }

  return false;
}

function isLegacyHeaderOrFooter(line) {
  const trimmed = line.trim();
  const normalized = trimmed.toLowerCase();

  if (!trimmed) {
    return false;
  }

  if (
    normalized === "fuuka-chan" ||
    normalized === `${settings.botName.toLowerCase()}-chan` ||
    normalized === "bot master-a" ||
    normalized === "ely - by arasea"
  ) {
    return true;
  }

  if (
    normalized.includes("fuuka imut") ||
    normalized.includes("fuuka kawaii") ||
    normalized.includes("fuuka dieum") ||
    normalized.includes("fuuka imoet") ||
    normalized.includes("fuuka imot") ||
    normalized.includes("fuuka imut selalu di hati") ||
    normalized.includes("nge-fans yaa sama fuuka") ||
    normalized.includes("semangat mq nya") ||
    normalized.includes("by: master-a") ||
    normalized.includes("by master-a")
  ) {
    return true;
  }

  return false;
}

function normalizeSpacing(text) {
  const lines = String(text)
    .split("\n")
    .map((line) => line.trimEnd())
    .filter((line) => !isLegacyDivider(line))
    .filter((line) => !isLegacyHeaderOrFooter(line));

  const compactLines = [];

  for (const line of lines) {
    const previousLine = compactLines[compactLines.length - 1];

    if (line === "" && previousLine === "") {
      continue;
    }

    compactLines.push(line);
  }

  return compactLines.join("\n").trim();
}

function formatHelpMessage(content, topicKey = "default") {
  const body = normalizeSpacing(content);
  const [greetingLine, supportLine] = getRandomGreetingLines();
  const introLine = getRandomIntro(topicKey);
  const bodyLines = body.split("\n");
  const visibleTitle = bodyLines[0] || "";
  const hiddenBody = bodyLines.slice(1).join("\n").trim();

  return [
    greetingLine,
    supportLine,
    `${introLine}`,
    "",
    divider,
    visibleTitle,
    divider,
    hiddenBody ? readMoreSeparator : "",
    hiddenBody ? "" : "",
    hiddenBody,
    hiddenBody ? divider : "",
    "",
    getRandomCuteFooter()
  ].filter((line, index, array) => {
    if (line !== "") {
      return true;
    }

    return array[index - 1] !== "";
  }).join("\n");
}

